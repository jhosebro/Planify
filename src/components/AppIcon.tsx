export interface AppIconProps {
  name: IconName;
  size?: number;
  color?: string;
  strokeWidth?: number;
  style?: StyleProp<ViewStyle>;
}

export function AppIcon({ name, size = 20, color, strokeWidth = 2, style }: AppIconProps) {
  const colors = useThemeColors();
  const Icon = ICONS[name];

  return (
    <Icon
      size={size}
      color={color ?? colors.textSecondary}
      strokeWidth={strokeWidth}
      style={style}
    />
  );
}

/**
 * Resolves a stored icon value (new semantic key or legacy emoji) to an IconName.
 */
export function resolveIconName(value?: string | null, fallback: IconName = 'circle-check'): IconName {
  if (!value) return fallback;
  if (value in ICONS) return value as IconName;
  return LEGACY_EMOJI_ICONS[value] ?? fallback;
}

export interface StoredIconProps extends Omit<AppIconProps, 'name'> {
  value?: string | null;
  fallback?: IconName;
}

/**
 * Renders an icon stored in the database, supporting both semantic keys and legacy emojis.
 */
export function StoredIcon({ value, fallback, ...props }: StoredIconProps) {
  return <AppIcon name={resolveIconName(value, fallback)} {...props} />;
}
